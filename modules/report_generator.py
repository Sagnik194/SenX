
from io import BytesIO

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


def generate_pdf_report(summary, filename="SenX_Business_Report"):
    """Generate an executive business summary as a PDF."""

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "SenXTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        fontSize=22,
        spaceAfter=10,
    )

    subtitle_style = ParagraphStyle(
        "SenXSubtitle",
        parent=styles["Normal"],
        alignment=TA_CENTER,
        fontSize=10,
        textColor=colors.grey,
    )

    elements = []

    elements.append(Paragraph("SenX", title_style))
    elements.append(
        Paragraph("Business Intelligence Executive Report", subtitle_style)
    )
    elements.append(Spacer(1, 25))

    elements.append(Paragraph("Executive Summary", styles["Heading2"]))
    elements.append(Spacer(1, 10))

    report_data = [
        ["Business Metric", "Value"],
        ["Total Revenue", f"{summary.get('total_revenue', 0):,.2f}"],
        ["Total Profit", f"{summary.get('total_profit', 0):,.2f}"],
        ["Total Orders", f"{summary.get('total_orders', 0):,}"],
        ["Total Customers", f"{summary.get('total_customers', 0):,}"],
        ["Average Order Value", f"{summary.get('average_order_value', 0):,.2f}"],
        ["Profit Margin", f"{summary.get('profit_margin', 0):.2f}%"],
        ["Total Quantity Sold", f"{summary.get('total_quantity', 0):,}"],
        ["Total Records", f"{summary.get('total_records', 0):,}"],
    ]

    table = Table(report_data, colWidths=[250, 200])

    table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#17365D")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
            ("PADDING", (0, 0), (-1, -1), 9),
            ("ALIGN", (1, 1), (1, -1), "RIGHT"),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1),
             [colors.white, colors.HexColor("#F2F5F9")]),
        ])
    )

    elements.append(table)
    elements.append(Spacer(1, 25))

    elements.append(Paragraph("Report Information", styles["Heading2"]))
    elements.append(
        Paragraph(
            "This report was generated by SenX Business Intelligence "
            "and Analytics Platform using the selected dataset stored "
            "in the MySQL database.",
            styles["Normal"],
        )
    )

    document.build(elements)

    buffer.seek(0)
    return buffer.getvalue()


def generate_excel_report(headers, rows, summary):
    """Generate an Excel workbook containing summary and source data."""

    workbook = Workbook()

    # Sheet 1: Executive Summary
    summary_sheet = workbook.active
    summary_sheet.title = "Executive Summary"

    summary_sheet.append(["SenX - Business Intelligence Report"])
    summary_sheet.append([])
    summary_sheet.append(["Business Metric", "Value"])

    metrics = [
        ("Total Revenue", summary.get("total_revenue", 0)),
        ("Total Profit", summary.get("total_profit", 0)),
        ("Total Orders", summary.get("total_orders", 0)),
        ("Total Customers", summary.get("total_customers", 0)),
        ("Average Order Value", summary.get("average_order_value", 0)),
        ("Profit Margin (%)", summary.get("profit_margin", 0)),
        ("Total Quantity Sold", summary.get("total_quantity", 0)),
        ("Total Records", summary.get("total_records", 0)),
    ]

    for metric, value in metrics:
        summary_sheet.append([metric, value])

    summary_sheet["A1"].font = Font(
        bold=True, size=16, color="FFFFFF"
    )
    summary_sheet["A1"].fill = PatternFill(
        "solid", fgColor="17365D"
    )

    for cell in summary_sheet[3]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="305496")

    summary_sheet.column_dimensions["A"].width = 28
    summary_sheet.column_dimensions["B"].width = 22

    # Sheet 2: Complete Dataset
    data_sheet = workbook.create_sheet("Sales Data")

    data_sheet.append(headers)

    for row in rows:
        data_sheet.append([
            str(row.get(header, "") or "")
            for header in headers
        ])

    for cell in data_sheet[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="17365D")
        cell.alignment = Alignment(horizontal="center")

    data_sheet.freeze_panes = "A2"
    data_sheet.auto_filter.ref = data_sheet.dimensions

    for column in data_sheet.columns:
        column_letter = column[0].column_letter
        data_sheet.column_dimensions[column_letter].width = min(
            max(
                len(str(cell.value or ""))
                for cell in list(column)[:100]
            ) + 3,
            35,
        )

    buffer = BytesIO()
    workbook.save(buffer)
    buffer.seek(0)

    return buffer.getvalue()
